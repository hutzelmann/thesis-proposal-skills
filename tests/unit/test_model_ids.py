def check(path: str, text: str) -> list[Violation]:
    return violations(path, text, FIXTURE_REGISTRY, PATTERN)


def test_recognizes_base_families_and_registry_lines():
    text = "run `openrouter/openai/gpt-6.1-sol`, then mistral-large-3, kimi-k3 and gemini-3.\n"
    assert [t for _, t in tokens(text, PATTERN)] == [
        "openrouter/openai/gpt-6.1-sol", "mistral-large-3", "kimi-k3", "gemini-3",
    ]


def test_rule_a_rejects_even_a_current_id_in_code():
    found = check("harness/new_module.py", 'JUDGE = "openrouter/anthropic/claude-haiku-4.5"\n')
    assert len(found) == 1
    message = found[0].message
    assert "harness/new_module.py:1" in message
    assert "openrouter/anthropic/claude-haiku-4.5" in message
    assert "Rule A" in message
    assert check(".github/workflows/x.yml", "model: gpt-6.1-sol\n")
    assert check("pyproject.toml", 'smoke = "--models claude-haiku-4.5"\n')
    assert not is_rule_a("harness/models.toml"), "the registry is where IDs belong"


