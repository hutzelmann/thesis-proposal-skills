"""L0 guard: model identifiers live only in the registry (testing-harness spec).

Every model ID the harness uses comes from `harness/models.toml`. A copy anywhere
else goes stale on its own: in July a hardcoded judge, a derived persona and two
documentation examples each named a model generation the roster had left. Two
rules, over every tracked file:

- **Rule A, no literal.** Harness and repository scripts, `harness/*.toml` other
  than the registry, `pyproject.toml` and the CI workflows carry no model ID at
  all, comments and docstrings included. A model name in code is either a
  default (a second source of truth) or an example that will rot.
- **Rule B, current or nothing.** Any other tracked file may name a model only
  by an ID that resolves to a current roster entry or role, in any accepted
  spelling: provider-qualified, provider-stripped, or the subscription CLI's
  dashed form. Docs keep runnable examples, but an example cannot outlive its
  pin: the weekly bump PR goes red here, naming each file that still cites an
  outgoing ID.

The allowlist below names every exemption with its reason. A parked entry (one
another change removes) and an entry for a single identifier fail once they
exempt nothing; category entries stay, because their files are clean only until
the next bump.

The IDs in this file are the guard's own fixtures, which is why it exempts itself.
"""

from __future__ import annotations

import fnmatch
import re
from dataclasses import dataclass

import model_currency as mc
import pytest
import support
from helpers import REPO, shipped_registry, tracked_files

# the vendor families the harness has used; the registry's own lines are added
# to these at scan time, so a new vendor is covered without editing this list
BASE_HEADS = (
    r"claude-(?:haiku|sonnet|opus|fable)-\d", r"gpt-\d", r"deepseek-v\d", r"qwen\d",
    r"kimi-k\d", r"gemini-\d",
)

RULE_A = (
    "harness/*.py", "harness/**/*.py", "scripts/*.py", "scripts/**/*.py",
    "harness/*.toml", "harness/**/*.toml", "pyproject.toml", ".github/workflows/*.yml",
)
RULE_A_EXCEPT = ("harness/models.toml",)

README_REGION = (support.START_MARKER, support.END_MARKER)


@dataclass(frozen=True)
class Allow:
    path: str  # fnmatch glob over repository-relative POSIX paths
    reason: str
    token: str = ""  # exempt only this identifier in that file
    owner: str = ""  # parked: the change that removes this entry

    @property
    def exhaustible(self) -> bool:
        """Parked and single-identifier entries must keep exempting something."""
        return bool(self.token or self.owner)


ALLOWLIST = (
    Allow("harness/models.toml", "the registry itself"),
    Allow("openspec/changes/**", "change records describe ID transitions, the archive included"),
    Allow("openspec/specs/**",
          "spec scenarios carry illustrative IDs, receive them when a change is archived, and "
          "change only through a change record, so a bump PR could never fix one"),
    Allow("docs/model-support.md", "generated by `uv run poe report`"),
    Allow("docs/skill-routing.md",
          "generated by `uv run poe routing`; records the served model as measured, which an "
          "alias can resolve to outside the roster"),
    Allow("shared/model-support.json", "generated by `uv run poe report`"),
    Allow("skills/*/references/model-support.json", "generated copy (scripts/sync_shared.py)"),
    Allow("skills/*/evals/evals.json", "generated eval projection (harness/eval_export.py)"),
    Allow("tests/unit/data/model_catalog/**", "the recorded catalog snapshot"),
    Allow("tests/unit/test_troubleshoot_collect.py",
          "model-identifier normalization test data; keeps old IDs for its version-guard tests"),
    Allow("tests/unit/test_model_currency.py",
          "currency tests over the recorded snapshot: their IDs are facts of that snapshot"),
    Allow("tests/unit/test_model_ids.py", "this guard's own fixtures"),
    Allow("harness/skill_evals.py",
          "troubleshoot_model_rung scenario: the user reports the model whose shipped verdict "
          "rung 1 looks up, in the spelling Claude Code reports",
          token="claude-haiku-4-5-20251001"),
    Allow("skills/proposal-troubleshoot/scripts/collect.py",
          "a comment illustrating that a dotted cloud-prefix segment holding a digit belongs to "
          "the model name; it names no model",
          token="qwen3"),
)


@dataclass(frozen=True)
class Violation:
    path: str
    line: int
    token: str
    message: str


# ---------- recognition and resolution ------------------------------------------


def registry_ids(registry: support.Registry) -> list[str]:
    roles = registry.roles
    return [*(m.id for m in registry.models),
            roles.judge, roles.persona, roles.smoke, roles.dev_judge]


def token_pattern(registry: support.Registry) -> re.Pattern[str]:
    heads = set(BASE_HEADS)
    for model_id in registry_ids(registry):
        line = mc.derive_line(mc.catalog_id(model_id))
        if line:
            heads.add(re.escape(line.split("/", 1)[1].split("*", 1)[0]) + r"\d")
    alternation = "|".join(sorted(heads))
    return re.compile(
        rf"(?<![\w.-])(?:openrouter/)?(?:[a-z0-9][a-z0-9-]*/)?(?:{alternation})[0-9A-Za-z.-]*"
    )


def tokens(text: str, pattern: re.Pattern[str]) -> list[tuple[int, str]]:
    found = []
    for number, line in enumerate(text.splitlines(), start=1):
        for match in pattern.finditer(line):
            token = match.group(0).rstrip(".-")
            found.append((number, token))
    return found


def current_ids(registry: support.Registry) -> set[str]:
    return {mc.catalog_id(model_id) for model_id in registry_ids(registry)}


def resolves(token: str, registry: support.Registry) -> bool:
    cid = mc.catalog_id(token)
    current = current_ids(registry)
    if "/" in cid:
        return cid in current
    return cid in {c.split("/", 1)[1] for c in current}


def current_pin(token: str, registry: support.Registry) -> str | None:
    """The registry ID that pins the token's version line, if any."""
    cid = mc.catalog_id(token)
    line = mc.derive_line(cid if "/" in cid else "/" + cid)
    if line is None:
        return None
    name = line.split("/", 1)[1]
    for model_id in registry_ids(registry):
        pinned = mc.derive_line(mc.catalog_id(model_id))
        if pinned and (pinned == line or ("/" not in cid and pinned.split("/", 1)[1] == name)):
            return model_id
    return None


def is_rule_a(path: str) -> bool:
    return path not in RULE_A_EXCEPT and any(fnmatch.fnmatch(path, g) for g in RULE_A)


def strip_generated_region(path: str, text: str) -> str:
    """Blank the README's generated model-support region, keeping line numbers."""
    start, end = README_REGION
    if path != "README.md" or start not in text or end not in text:
        return text
    head, rest = text.split(start, 1)
    region, tail = rest.split(end, 1)
    return head + start + "\n" * region.count("\n") + end + tail


def violations(path: str, text: str, registry: support.Registry,
               pattern: re.Pattern[str]) -> list[Violation]:
    text = strip_generated_region(path, text)
    found = []
    rule_a = is_rule_a(path)
    for number, token in tokens(text, pattern):
        if rule_a:
            message = ("Rule A: no model ID in harness/scripts code or config — take it from "
                       "harness/models.toml ([roles] or the roster)")
        elif resolves(token, registry):
            continue
        elif (pin := current_pin(token, registry)) is not None:
            message = f"Rule B: not a current registry model — its line is pinned at `{pin}`"
        else:
            message = "Rule B: no roster entry or role tracks this model"
        found.append(Violation(path, number, token, f"{path}:{number}: `{token}` — {message}"))
    return found


def exempting(violation: Violation) -> list[Allow]:
    return [
        a for a in ALLOWLIST
        if fnmatch.fnmatch(violation.path, a.path) and (not a.token or a.token == violation.token)
    ]


# ---------- the scan --------------------------------------------------------------


def _scan() -> list[Violation]:
    registry = shipped_registry()
    pattern = token_pattern(registry)
    found = []
    for rel in tracked_files():
        try:
            text = (REPO / rel).read_text(encoding="utf-8")
        except (UnicodeDecodeError, FileNotFoundError, IsADirectoryError):
            continue
        found.extend(violations(rel, text, registry, pattern))
    return found


@pytest.fixture(scope="module")
def scan() -> list[Violation]:
    return _scan()


def test_model_ids_live_only_in_the_registry(scan):
    open_violations = [v.message for v in scan if not exempting(v)]
    assert not open_violations, (
        "model identifiers outside the registry (see the docstring of "
        "tests/unit/test_model_ids.py for the rules):\n  " + "\n  ".join(open_violations)
    )


def test_no_allowlist_entry_outlives_its_cause(scan):
    used = {id(a) for v in scan for a in exempting(v)}
    dead = [a for a in ALLOWLIST if a.exhaustible and id(a) not in used]
    assert not dead, "allowlist entries that exempt nothing any more — remove them:\n  " + (
        "\n  ".join(f"{a.path} {a.token!r} (owner: {a.owner or 'permanent'})" for a in dead))


def test_every_allowlist_entry_gives_its_reason():
    for entry in ALLOWLIST:
        assert entry.reason.strip(), entry
    parked = [a for a in ALLOWLIST if a.owner]
    assert all(a.token for a in parked), "a parked entry names the identifier it tolerates"


def test_the_scan_covers_the_tree():
    """Guards the guard: an empty `git ls-files` would make the scan vacuous."""
    assert len(tracked_files()) > 200


